# Earlier products used S2A in the name; the current products use L1A.
# make_slc_lt1 reads both layouts, so discovery accepts both identifiers.
PRODUCT_RE = re.compile(r"^(LT1[AB])_.*_(\d{8})_SLC_[^_]+_(?:L1A|S2A)_.*$")
SCALE_RE = re.compile(r"closer\s+to\s+([-+0-9.eE]+)", re.IGNORECASE)


@dataclass(frozen=True)
class Scene:
    stem: str
    satellite: str
    date: str
    directory: Path
    metadata: Path
    raster: Path
    orbit: Path | None

    @property
    def output_stem(self) -> str:
        """Short GMTSAR name requested for PRM/SLC/LED and data.list."""
        return f"LT1_{self.date}"


@dataclass(frozen=True)
class OrbitPoint:
    time: dt.datetime
    position: tuple[float, float, float]
    velocity: tuple[float, float, float]


